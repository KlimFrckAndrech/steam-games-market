export function initInfoModals() {
  document.addEventListener("click", (e) => {
    const trigger = e.target.closest("[data-modal]");
    if (!trigger) return;
    const content = TEXTS[trigger.dataset.modal];
    if (!content) return;
    openModal({
      title: content.title,
      trigger,
      fill(body) {
        for (const text of content.paragraphs) {
          const p = document.createElement("p");
          p.textContent = text;
          body.append(p);
        }
      },
    });
  });
}
